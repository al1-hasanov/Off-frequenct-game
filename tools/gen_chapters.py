#!/usr/bin/env python3
"""Build scripts/chapter_states.gd (debug chapter select) from four playthroughs.

Each automated playthrough can record the exact story state at the start of
every chapter:

    godot --headless --path . -- --autotest=answer       --chapters=ch_answer.json
    godot --headless --path . -- --autotest=answer_leave --chapters=ch_answer_leave.json
    godot --headless --path . -- --autotest=cut_take     --chapters=ch_cut_take.json
    godot --headless --path . -- --autotest=cut          --chapters=ch_cut.json
    python3 tools/gen_chapters.py ch_*.json

A chapter whose state is the same in all four runs gets one state ("any").
One that only depends on Choice 1 gets "answer" and "cut". Anything else
gets all four combinations.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "scripts" / "chapter_states.gd"


def canon(x):
    return json.dumps(x, sort_keys=True)


def main(paths):
    runs = {}
    for p in paths:
        d = json.loads(Path(p).read_text())
        runs[(d["answered"], d["take_tomas"])] = d["chapters"]
    combos = [(True, True), (True, False), (False, True), (False, False)]
    missing = [c for c in combos if c not in runs]
    if missing:
        sys.exit(f"need all four playthroughs, missing {missing}")

    ids = list(runs[(True, True)].keys())
    for c in combos:
        if list(runs[c].keys()) != ids:
            sys.exit(f"run {c} recorded different chapters: {list(runs[c].keys())}")

    out = {}
    for cid in ids:
        s = {c: runs[c][cid] for c in combos}
        if len({canon(v) for v in s.values()}) == 1:
            out[cid] = {"any": s[(True, True)]}
            kind = "any"
        elif all(canon(s[(a, True)]) == canon(s[(a, False)]) for a in (True, False)):
            out[cid] = {"answer": s[(True, True)], "cut": s[(False, False)]}
            kind = "choice 1"
        else:
            out[cid] = {
                ("answer" if a else "cut") + ("_take" if t else "_leave"): s[(a, t)]
                for a, t in combos
            }
            kind = "both choices"
        first = next(iter(out[cid].values()))
        print(f"  {cid:4} {first['room']:15} {first['frequency']:3} {kind}")

    body = json.dumps(out, indent="\t", ensure_ascii=False)
    OUT.write_text(
        "class_name ChapterStates\n"
        "## GENERATED by tools/gen_chapters.py from four automated playthroughs.\n"
        "## Don't edit by hand: rerun the playthroughs with --chapters and regenerate.\n"
        "## Each entry is a save-game snapshot taken as the chapter's first room loads.\n\n"
        f"const STATES := {body}\n"
    )
    print(f"wrote {OUT} ({len(out)} chapters)")


if __name__ == "__main__":
    main(sys.argv[1:])
